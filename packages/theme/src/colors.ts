const tokenName = (name: string) => name.replace(/[A-Z]/g, (letter) => '-' + letter.toLowerCase())
const declarations = (prefix: string, values: Record<string, string>) =>
  Object.entries(values).map(([name, value]) => '\n  --' + prefix + '-' + tokenName(name) + ': ' + value + ';').join('')

